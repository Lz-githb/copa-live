def fix(path):
    with open(path, 'rb') as f:
        rom = bytearray(f.read())

    # Garante tamanho mínimo de 192 bytes
    while len(rom) < 192:
        rom.append(0)

    # Insere logo (offsets 0x04 a 0x9F)
    rom[0x04:0x04+len(NINTENDO_LOGO)] = NINTENDO_LOGO

    # Título do jogo (12 bytes, offset 0xA0)
    title = b'JOGO DA VELHA'[:12].ljust(12, b'\x00')
    rom[0xA0:0xAC] = title

    # Game code (4 bytes) + maker code (2 bytes)
    rom[0xAC:0xB0] = b'JVLP'
    rom[0xB0:0xB2] = b'LZ'

    # Fixed values
    rom[0xB2] = 0x96  # fixed (obrigatório pelo hardware GBA)
    rom[0xB3] = 0x00  # unit code
    rom[0xB4] = 0x00  # device type
    rom[0xBC] = 0x00  # version

    # Checksum (header complement, bytes 0xA0-0xBC)
    chk = 0
    for b in rom[0xA0:0xBD]:
        chk = (chk - b) & 0xFF
    chk = (chk - 0x19) & 0xFF
    rom[0xBD] = chk

    with open(path, 'wb') as f:
        f.write(rom)
    print(f"Header corrigido: checksum=0x{chk:02X}")

if __name__ == '__main__':
    fix(sys.argv[1])
