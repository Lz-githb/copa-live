static void draw_char(int x, int y, char c, uint8_t col) {
    if (c>='a'&&c<='z') c-=32;
    if (c<' '||c>'Z') return;
    const uint8_t *g=FONT5X7[c-' '];
    for(int r=0;r<7;r++) {
        uint8_t bits=g[r];
        for(int cx=0;cx<5;cx++)
            if(bits&(1<<(4-cx))) m4_pixel(x+cx,y+r,col);
    }
}

static void draw_str(int x, int y, const char *s, uint8_t col) {
    while(*s){draw_char(x,y,*s,col);x+=6;s++;}
}

static void draw_int(int x, int y, int val, uint8_t col) {
    char buf[12]; int i=10; buf[11]=0;
    if(val==0){draw_char(x,y,'0',col);return;}
    while(val>0&&i>=0){buf[i--]='0'+(val%10);val/=10;}
    draw_str(x,y,buf+i+1,col);
}

static void draw_str_centered(int y, const char *s, uint8_t col) {
    int len=0; for(const char*p=s;*p;p++)len++;
    draw_str((SCREEN_W-len*6)/2,y,s,col);
}
