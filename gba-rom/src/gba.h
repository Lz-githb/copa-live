// --- Input helpers ---
static inline uint16_t key_down(void) {
    return ~REG_KEYINPUT & 0x03FF;
}

static uint16_t _prev_keys = 0;
static inline uint16_t key_pressed(void) {
    uint16_t cur = key_down();
    uint16_t p = cur & ~_prev_keys;
    _prev_keys = cur;
    return p;
}

// --- VBlank wait ---
static inline void vsync(void) {
    while (REG_VCOUNT >= 160);
    while (REG_VCOUNT < 160);
}

// --- Mode 3 pixel drawing ---
static inline void m3_pixel(int x, int y, uint16_t col) {
    if ((unsigned)x < SCREEN_W && (unsigned)y < SCREEN_H)
        VRAM[y * SCREEN_W + x] = col;
}

// DMA fill — fastest possible VRAM clear (32-bit, fixed src, immediate)
// CNT_H = 0x8580: enable | 32bit | src-fixed | dest-inc | immediate
static volatile uint32_t _dma_fill_src;
static inline void m3_fill(uint16_t col) {
    _dma_fill_src = col | ((uint32_t)col << 16);
    DMA3SAD = (uint32_t)&_dma_fill_src;
    DMA3DAD = (uint32_t)VRAM;
    // CNT_H: bit15=enable, bit10=32bit, bits8-7=10(src-fixed), bits6-5=00(dst-inc)
    DMA3CNT = (SCREEN_W * SCREEN_H / 2) | (0x8500u << 16);
    // wait until DMA completes
    while (DMA3CNT & (1u << 31));
}

static inline void m3_rect(int x, int y, int w, int h, uint16_t col) {
    for (int dy = 0; dy < h; dy++)
        for (int dx = 0; dx < w; dx++)
            m3_pixel(x+dx, y+dy, col);
}

static inline void m3_hline(int x, int y, int w, uint16_t col) {
    for (int i = 0; i < w; i++) m3_pixel(x+i, y, col);
}

static inline void m3_vline(int x, int y, int h, uint16_t col) {
    for (int i = 0; i < h; i++) m3_pixel(x, y+i, col);
}

static inline void m3_border(int x, int y, int w, int h, uint16_t col) {
    m3_hline(x, y, w, col);
    m3_hline(x, y+h-1, w, col);
    m3_vline(x, y, h, col);
    m3_vline(x+w-1, y, h, col);
}

// --- Simple pseudo-random ---
static uint32_t _rng_seed = 0xDEADBEEF;
static inline uint32_t rng(void) {
    _rng_seed ^= _rng_seed << 13;
    _rng_seed ^= _rng_seed >> 17;
    _rng_seed ^= _rng_seed << 5;
    return _rng_seed;
}
static inline int rng_range(int lo, int hi) {
    return lo + (int)(rng() % (uint32_t)(hi - lo));
}

// --- Integer abs ---
static inline int iabs(int x) { return x < 0 ? -x : x; }
static inline int imin(int a, int b) { return a < b ? a : b; }
static inline int imax(int a, int b) { return a > b ? a : b; }
static inline int iclamp(int v, int lo, int hi) { return v < lo ? lo : v > hi ? hi : v; }

