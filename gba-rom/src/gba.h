#pragma once
#include <stdint.h>

// --- Hardware registers ---
#define REG_DISPCNT  (*(volatile uint16_t*)0x04000000)
#define REG_VCOUNT   (*(volatile uint16_t*)0x04000006)
#define REG_KEYINPUT (*(volatile uint16_t*)0x04000130)

// DMA channel 3
#define DMA3SAD (*(volatile uint32_t*)0x040000D4)
#define DMA3DAD (*(volatile uint32_t*)0x040000D8)
#define DMA3CNT (*(volatile uint32_t*)0x040000DC)

// Display mode 4: 8bpp indexed, double-buffered
#define DCNT_MODE4  0x0004
#define DCNT_BG2    (1<<10)
#define DCNT_PAGE1  (1<<4)

// Keys
#define KEY_A      (1<<0)
#define KEY_B      (1<<1)
#define KEY_SELECT (1<<2)
#define KEY_START  (1<<3)
#define KEY_RIGHT  (1<<4)
#define KEY_LEFT   (1<<5)
#define KEY_UP     (1<<6)
#define KEY_DOWN   (1<<7)
#define KEY_R      (1<<8)
#define KEY_L      (1<<9)

#define SCREEN_W 240
#define SCREEN_H 160

// Mode 4 pages
#define PAGE0 ((uint8_t*)0x06000000)
#define PAGE1 ((uint8_t*)0x0600A000)

// BG palette RAM (256 x RGB15)
#define PAL_BG ((volatile uint16_t*)0x05000000)

#define RGB15(r,g,b) ((r)|((g)<<5)|((b)<<10))

// ---- Double-buffer state ----
static uint8_t *draw_buf;   // back buffer: we draw here

static inline void vsync(void) {
    while (REG_VCOUNT >= 160);
    while (REG_VCOUNT < 160);
}

// Wait for VBlank, then flip pages
static inline void flip(void) {
    vsync();
    REG_DISPCNT ^= DCNT_PAGE1;
    draw_buf = (REG_DISPCNT & DCNT_PAGE1) ? PAGE0 : PAGE1;
}

// ---- Input ----
static uint16_t _prev_keys;
static inline uint16_t key_down(void)    { return ~REG_KEYINPUT & 0x03FF; }
static inline uint16_t key_pressed(void) {
    uint16_t cur = key_down(), p = cur & ~_prev_keys;
    _prev_keys = cur; return p;
}

// ---- RNG ----
static uint32_t _rng = 0xDEADBEEF;
static inline uint32_t rng(void) {
    _rng ^= _rng<<13; _rng ^= _rng>>17; _rng ^= _rng<<5; return _rng;
}
static inline int rng_range(int lo, int hi) { return lo+(int)(rng()%(unsigned)(hi-lo)); }

// ---- Math ----
static inline int iabs(int x)              { return x<0?-x:x; }
static inline int imin(int a, int b)       { return a<b?a:b; }
static inline int imax(int a, int b)       { return a>b?a:b; }
static inline int iclamp(int v, int l, int h) { return v<l?l:v>h?h:v; }

// ---- DMA fill (Mode 4: 9600 32-bit words = 38400 bytes) ----
static volatile uint32_t _dma_src;
static inline void m4_fill(uint8_t col) {
    uint32_t c = col;
    _dma_src = c|(c<<8)|(c<<16)|(c<<24);
    DMA3SAD = (uint32_t)&_dma_src;
    DMA3DAD = (uint32_t)draw_buf;
    // bits: enable|32bit|src-fixed = 0x8500
    DMA3CNT = (SCREEN_W*SCREEN_H/4)|(0x8500u<<16);
    while (DMA3CNT & (1u<<31));
}

// ---- Drawing (Mode 4 indexed, 8bpp) ----
static inline void m4_pixel(int x, int y, uint8_t col) {
    if ((unsigned)x>=SCREEN_W||(unsigned)y>=SCREEN_H) return;
    uint16_t *p = (uint16_t*)draw_buf + y*120 + x/2;
    if (x&1) *p = (*p&0x00FF)|((uint16_t)col<<8);
    else     *p = (*p&0xFF00)|col;
}

static inline void m4_hline(int x, int y, int w, uint8_t col) {
    if ((unsigned)y>=SCREEN_H||x>=SCREEN_W||x+w<=0) return;
    if (x<0){w+=x;x=0;} if(x+w>SCREEN_W)w=SCREEN_W-x; if(w<=0)return;
    uint16_t pair=col|((uint16_t)col<<8);
    uint16_t *row=(uint16_t*)draw_buf+y*120;
    if (x&1){uint16_t*p=row+x/2;*p=(*p&0x00FF)|((uint16_t)col<<8);x++;w--;}
    uint16_t *p=row+x/2; int pairs=w/2;
    for(int i=0;i<pairs;i++) p[i]=pair;
    if(w&1){p=row+(x+w-1)/2;*p=(*p&0xFF00)|col;}
}

static inline void m4_vline(int x, int y, int h, uint8_t col) {
    for(int i=0;i<h;i++) m4_pixel(x,y+i,col);
}

static inline void m4_rect(int x, int y, int w, int h, uint8_t col) {
    for(int i=0;i<h;i++) m4_hline(x,y+i,w,col);
}

static inline void m4_border(int x, int y, int w, int h, uint8_t col) {
    m4_hline(x,y,w,col); m4_hline(x,y+h-1,w,col);
    m4_vline(x,y,h,col); m4_vline(x+w-1,y,h,col);
}

