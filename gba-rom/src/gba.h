// Screen
#define SCREEN_W      240
#define SCREEN_H      160

// Mode 3 VRAM - 16bpp direct color
#define VRAM          ((uint16_t*)0x06000000)

// Mode 4 page flip
#define PAGE0         ((uint16_t*)0x06000000)
#define PAGE1         ((uint16_t*)0x0600A000)

// Palette RAM (mode 4: BG palette)
#define PAL_BG        ((uint16_t*)0x05000000)

// GBA 15-bit BGR color: xBBBBBGGGGGRRRRR
#define RGB15(r,g,b)  ((r) | ((g)<<5) | ((b)<<10))

// OAM (sprites) - 128 objects, each 4x16-bit attrs
