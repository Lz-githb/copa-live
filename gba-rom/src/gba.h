static void draw_char(int x, int y, char c, uint16_t col) {
    if (c < 0x20 || c > 0x5A) return;
    const uint8_t *glyph = FONT5X7[c - 0x20];
    for (int row = 0; row < 7; row++) {
        uint8_t bits = glyph[row];
        for (int col2 = 0; col2 < 5; col2++) {
            if (bits & (1 << (4 - col2)))
                m3_pixel(x + col2, y + row, col);
        }
    }
}

static void draw_str(int x, int y, const char *s, uint16_t col) {
    while (*s) { draw_char(x, y, *s >= 'a' && *s <= 'z' ? *s-32 : *s, col); x += 6; s++; }
}

static void draw_int(int x, int y, int val, uint16_t col) {
    char buf[12]; int i = 10;
    buf[11] = 0;
    if (val == 0) { draw_char(x, y, '0', col); return; }
    while (val > 0 && i >= 0) { buf[i--] = '0' + (val % 10); val /= 10; }
    draw_str(x, y, buf + i + 1, col);
}

static void draw_str_centered(int y, const char *s, uint16_t col) {
    int len = 0; for (const char *p = s; *p; p++) len++;
    int x = (SCREEN_W - len * 6) / 2;
    draw_str(x, y, s, col);
}

// Number of characters in a decimal integer
static int int_digits(int v) {
    if (v == 0) return 1;
    int d = 0; while (v > 0) { d++; v /= 10; } return d;
}
