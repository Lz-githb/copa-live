/*
 * sprite_characters.c
 * Chronicles of Aetheria - GBA RPG
 *
 * Playable character sprite tile data and palettes.
 * 4 characters × 8 frames × 4 tiles = 128 tiles (OBJ tiles 0–127).
 *
 * Tile layout per frame:
 *   tile[frame*4+0]  tile[frame*4+1]   <- top half  (hair + head)
 *   tile[frame*4+2]  tile[frame*4+3]   <- bottom half (body + legs)
 *
 * Character order:
 *   CHAR_WARRIOR = 0  (tiles   0– 31)
 *   CHAR_MAGE    = 1  (tiles  32– 63)
 *   CHAR_ROGUE   = 2  (tiles  64– 95)
 *   CHAR_CLERIC  = 3  (tiles  96–127)
 *
 * Directions per character (8 frames = 4 dirs × 2 walk frames):
 *   frames 0,1 = DOWN  (south)
 *   frames 2,3 = UP    (north)
 *   frames 4,5 = LEFT  (west)
 *   frames 6,7 = RIGHT (east)
 *
 * Palette indices used in art:
 *   0  = transparent
 *   1  = skin/flesh
 *   2  = hair/dark
 *   3  = shirt/main color
 *   4  = pants/secondary
 *   5  = boots/dark
 *   6  = weapon/item
 *   7  = outline/shadow
 *   8  = highlight
 *   9  = eyes
 *  10  = belt/accent
 *  11  = cape/cloak
 *  12-15 = misc
 *
 * Row encoding: each u32 = 8 pixels, lower nibble = leftmost pixel
 *   ROW(p0,p1,p2,p3,p4,p5,p6,p7)
 */

