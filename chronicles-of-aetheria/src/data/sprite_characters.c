/* Returns the tile index (into g_char_tiles) for a character frame.
 * char_idx: 0-3, dir: 0=down,1=up,2=left,3=right, frame: 0-1
 * The returned value is also the OBJ tile number (char already at offset 0). */
u16 char_sprite_tile(u8 char_idx, u8 dir, u8 frame) {
    return (u16)(char_idx * 32u + dir * 8u + frame * 4u);
}

/* Load all character gfx into OBJ VRAM. */
void gfx_chars_load(void) {
    u8 i;
    for (i = 0; i < 4; i++)
        sprite_load_palette(i, g_char_palettes[i]);
    sprite_load_tiles(0, (const u32 *)g_char_tiles, 128);
}
