/* =========================================================
 * gfx_ui_load() — call once after engine_init()
 * Copies all tile and palette data into GBA VRAM/CRAM.
 * ========================================================= */
void gfx_ui_load(void)
{
    /* Palettes into BG palette RAM */
    tile_load_palette(0, pal_window);
    tile_load_palette(1, pal_border);
    tile_load_palette(2, pal_text);
    tile_load_palette(3, pal_hi);
    tile_load_palette(4, pal_dim);
    tile_load_palette(5, pal_hp);
    tile_load_palette(6, pal_mp);
    tile_load_palette(7, pal_exp);
    tile_load_palette(8, pal_cursor);

    /* Font: charblock 0, starting at tile 0 (= TILE_FONT_BASE) */
    tile_load_tileset(0, 0, (const u32*)font_tiles, 95 * 8);

    /* Window chrome: charblock 0, tile 128 */
    tile_load_tileset(0, 128, (const u32*)chrome_tiles, 20 * 8);

    /* Icons: charblock 0, tile 192 */
    tile_load_tileset(0, 192, (const u32*)icon_tiles, 19 * 8);
}
