/* =========================================================
 * Font tiles — 4bpp, 8x8
 * Each glyph: 8 rows × 8 pixels, 4 bits/pixel → 4 bytes/row → 8 u32s
 * Pixel 0 = palette index 0 (transparent), 2 = white text
 *
 * We store a minimal proportional 5×7 bitmap font converted to 4bpp.
 * Only printable ASCII 0x20–0x7E (95 chars, tiles 0–94).
 * ========================================================= */

